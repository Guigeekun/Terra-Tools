export const ROMAN_MAP = {
  'Ⅰ': ' I', 'Ⅱ': ' II', 'Ⅲ': ' III', 'Ⅳ': ' IV',
  'I': ' I', 'II': ' II', 'III': ' III', 'IV': ' IV'
};

export function translateStageTitleFallback(raw) {
  if (!raw) return '';
  const trimmed = String(raw).trim();
  if (EXACT_STAGE_TRANSLATIONS[trimmed]) {
    return EXACT_STAGE_TRANSLATIONS[trimmed];
  }

  let m = trimmed.match(/^\[誘いの塔\]\s*(.+?)(Ⅰ|Ⅱ|Ⅲ|Ⅳ|I|II|III|IV)?$/);
  if (m) {
    const base = m[1].trim();
    const num = m[2] || '';
    const enName = STAGE_NAME_MAP[base] || base;
    return `[Tower of Temptation] ${enName}${ROMAN_MAP[num] || num}`;
  }

  m = trimmed.match(/^\[るつぼの都\]\s*(.+?)\s*-\s*(\d+)$/);
  if (m) {
    const sp = m[1].trim();
    const num = m[2];
    const speciesMap = { 'ヒト': 'Human', 'トカゲ': 'Lizard', 'ケモノ': 'Beast', '岩人': 'Stonefolk' };
    const enSp = speciesMap[sp] || sp;
    return `[Melting Pot] ${enSp} - ${num}`;
  }

  m = trimmed.match(/^\[?逆襲降臨\]?\s*(.+?)\s+(初級|中級|上級|超級)$/);
  if (m) {
    const boss = m[1].trim();
    const diff = m[2].trim();
    const enBoss = STAGE_NAME_MAP[boss] || boss;
    const enDiff = STAGE_DIFF_MAP[diff] || diff;
    return `[Counterattack] ${enBoss} (${enDiff})`;
  }

  m = trimmed.match(/^逆襲降臨(\d+-\d+)$/);
  if (m) return `Counterattack ${m[1]}`;

  m = trimmed.match(/^リトルノア[：:]\s*(.+?)(Ⅰ|Ⅱ|Ⅲ|I|II|III)$/);
  if (m) {
    const boss = m[1].trim();
    const num = m[2];
    const enBoss = STAGE_NAME_MAP[boss] || boss;
    return `Little Noah: ${enBoss}${ROMAN_MAP[num] || num}`;
  }

  m = trimmed.match(/^五覇降臨\s*(.+?)(?:（|\()(ハード)(?:）|\))?$/);
  if (m) {
    const boss = m[1].trim();
    const enBoss = STAGE_NAME_MAP[boss] || boss;
    return `Descent of the Five: ${enBoss} (Hard)`;
  }

  m = trimmed.match(/^五覇降臨\s*(.+)$/);
  if (m) {
    const boss = m[1].trim();
    const enBoss = STAGE_NAME_MAP[boss] || boss;
    return `Descent of the Five: ${enBoss}`;
  }

  m = trimmed.match(/^(.+?)(Ⅰ|Ⅱ|Ⅲ|Ⅳ|I|II|III|IV)?(?:（|\()(シングル)(?:）|\))$/);
  if (m) {
    const boss = m[1].trim();
    const num = m[2] || '';
    const enBoss = STAGE_NAME_MAP[boss] || boss;
    return `${enBoss}${ROMAN_MAP[num] || num} (Single)`;
  }

  m = trimmed.match(/^(.+?)(Ⅰ|Ⅱ|Ⅲ|Ⅳ)$/); 
  if (m) {
    const boss = m[1].trim();
    const num = m[2];
    const enBoss = STAGE_NAME_MAP[boss] || boss;
    return `${enBoss}${ROMAN_MAP[num] || num}`;
  }

  m = trimmed.match(/^ブレアソール(\d+-\d+)$/);
  if (m) return `Braarsoul ${m[1]}`;

  m = trimmed.match(/^シンエン戦(\d+)$/);
  if (m) return `Shin'en Battle ${m[1]}`;

  m = trimmed.match(/^ムトウ戦(\d+)$/);
  if (m) return `Mutoh Battle ${m[1]}`;

  m = trimmed.match(/^メカチュラ物語(\d+)$/);
  if (m) return `Mechathura Tales ${m[1]}`;

  m = trimmed.match(/^FF15\s+(.+)$/);
  if (m) {
    const char = m[1].trim();
    const charMap = { 'グラディオラス': 'Gladiolus', 'イグニス': 'Ignis', 'プロンプト': 'Prompto' };
    return `FFXV: ${charMap[char] || char}`;
  }

  if (STAGE_NAME_MAP[trimmed]) return STAGE_NAME_MAP[trimmed];

  if (trimmed.includes(' ')) {
    const [first, ...rest] = trimmed.split(' ');
    const firstEn = EXACT_STAGE_TRANSLATIONS[first] || STAGE_NAME_MAP[first] || first;
    const restEn = rest.map(translateStageTitleFallback).join(' ');
    return `${firstEn} ${restEn}`;
  }

  return trimmed;
}


